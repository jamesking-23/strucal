//! Prints the engine's results for every module's default reference case as Markdown tables (used for the verification register).
use serde_json::{json, Map, Value};
use strucal_engine::modules;

fn main() {
    println!("<!-- generated by: cargo run -p strucal-engine --example verification_report ; engine v{} -->", strucal_engine::ENGINE_VERSION);
    for d in modules::defs() {
        let mut m = Map::new(); m.insert("mode".into(), json!("design")); m.insert("param_set".into(), json!("EN1992-1-1:2004/RECOMMENDED"));
        for f in &d.fields { if !f.check_only { m.insert(f.key.into(), json!(f.default)); } }
        let r = modules::run(d.id, &Value::Object(m.clone()));
        println!("\n### {} (`{}`)\n", d.title, d.id);
        println!("{}\n", d.subtitle);
        println!("**Default inputs**\n\n| Input | Value | Unit |\n|---|---|---|");
        for f in &d.fields { if !f.check_only { println!("| {} | {} | {} |", f.label, f.default, f.unit); } }
        if !r.ok { println!("\n*Default case did not run: {}*", r.errors.join("; ")); continue; }
        println!("\n**Engine results**\n\n| Result | Value |\n|---|---|");
        for k in &r.summary { println!("| {} | {} |", k.label, k.value); }
        if !r.checks.is_empty() {
            println!("\n**Checks**\n\n| Check | Clause | Demand | Capacity | Utilisation | Result |\n|---|---|---|---|---|---|");
            for c in &r.checks { println!("| {} | {} | {} | {} | {:.2} | {} |", c.name, c.reference, c.demand, c.capacity, c.utilisation, if c.pass { "PASS" } else { "FAIL" }); }
        } else { println!("\n*This module reports design values and has no PASS/FAIL checks.*"); }
        println!("\nTrace steps: {}; trace hash `{}`", r.trace.steps.len(), r.trace_hash);
    }
}
